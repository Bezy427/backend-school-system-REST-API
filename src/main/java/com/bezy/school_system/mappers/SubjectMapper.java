package com.bezy.school_system.mappers;

import com.bezy.school_system.dtos.RegisterSubjectRequest;
import com.bezy.school_system.dtos.SubjectDto;
import com.bezy.school_system.dtos.UpdateSubjectRequest;
import com.bezy.school_system.entities.Subject;
import org.mapstruct.BeanMapping;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.MappingTarget;
import org.mapstruct.NullValuePropertyMappingStrategy;

@Mapper(componentModel = "spring")
public interface SubjectMapper {

    // Entity -> DTO: the entity holds a Department object, the DTO wants only its id.
    @Mapping(source = "department.id", target = "departmentId")
    SubjectDto toDto(Subject subject);

    // Request -> new entity. The id is generated by the database.
    // The relationships can't come from a request, so the service sets the department.
    @Mapping(target = "id", ignore = true)
    @Mapping(target = "department", ignore = true)
    @Mapping(target = "attendances", ignore = true)
    @Mapping(target = "enrollments", ignore = true)
    @Mapping(target = "exams", ignore = true)
    Subject toEntity(RegisterSubjectRequest request);

    // Request -> EXISTING entity. @MappingTarget makes the second parameter
    // the object being updated, not a second source.
    // Fields left null in the request keep their current value.
    @BeanMapping(nullValuePropertyMappingStrategy = NullValuePropertyMappingStrategy.IGNORE)
    @Mapping(target = "id", ignore = true)
    @Mapping(target = "department", ignore = true)
    @Mapping(target = "attendances", ignore = true)
    @Mapping(target = "enrollments", ignore = true)
    @Mapping(target = "exams", ignore = true)
    void update(UpdateSubjectRequest request, @MappingTarget Subject subject);
}